"""Regenerate experiments/LEADERBOARD.md from experiments/runs/*.json. Never edit the board by hand.

Usage: .venv/bin/python scripts/make_leaderboard.py [--runs-dir experiments/runs] [--out ...]

One table per evaluation set (scores on different match sets aren't comparable), sorted by spellF1.
src.evaluate runs it after recording a run. It reads both src.evaluate run files and the older
hand-written ones (config with params inline, eval as a free-text label).
"""

from __future__ import annotations

import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from src.report.runs import RUNS_DIR, eval_label, load_runs, params_text  # noqa: E402,F401

def switch_text(metrics: dict) -> str:
    """"0.31/0.42" from a run's switch precision / recall (B16), "-" when not recorded."""
    p, r = metrics.get("switch_precision"), metrics.get("switch_recall")
    if p is None and r is None:
        return "-"
    return "/".join("-" if v is None else "{:.2f}".format(v) for v in (p, r))


def render(runs: list[dict]) -> str:
    groups = {}
    for run in runs:
        groups.setdefault(eval_label(run), []).append(run)
    # Biggest evaluation sets first: those are the numbers to trust (findings F6).
    order = sorted(groups, key=lambda g: (-max(len(r.get("eval", [])) for r in groups[g]), g))

    lines = ["# Leaderboard", "",
             "Generated by `scripts/make_leaderboard.py` from `experiments/runs/`. **Don't edit by "
             "hand.** External matches only. spellF1 is the ranking metric (mean over matches); "
             "range is the worst and best match. Spells = predicted / true possessions per match. "
             "Switch P/R = H<->A switch precision / recall at +/-1 s (findings F61-F62; a "
             "diagnostic, not a target; - for runs recorded before B16).",
             ""]
    for group in order:
        lines += ["## " + group, "",
                  "| # | spellF1 | range | macroF1 | spells | switch P/R | model | params | mode | run | commit |",
                  "|---|---|---|---|---|---|---|---|---|---|---|"]
        ranked = sorted(groups[group], key=lambda r: (-r["metrics"]["spellF1"], r["_file"]))
        for rank, run in enumerate(ranked, 1):
            m, config = run["metrics"], run.get("config") or {}
            low, high = m.get("spellF1_min"), m.get("spellF1_max")
            spells = "{}/{}".format(m.get("n_poss_pred_mean", m.get("n_poss_pred", "?")),
                                    m.get("n_poss_true_mean", m.get("n_poss_true", "?")))
            lines.append("| {} | **{:.4f}** | {} | {} | {} | {} | {} | {} | {} | [{}](runs/{}) | {} |".format(
                rank, m["spellF1"],
                "{:.3f}-{:.3f}".format(low, high) if low is not None else "-",
                "{:.4f}".format(m["macroF1"]) if "macroF1" in m else "-",
                spells, switch_text(m), config.get("model", "?"), params_text(config).replace("|", "/"),
                config.get("mode", "-"), run["id"], run["_file"], run.get("commit", "?")))
        lines.append("")
    if not groups:
        lines.append("_No runs yet._")
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> str:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--runs-dir", default=RUNS_DIR)
    parser.add_argument("--out", help="default: LEADERBOARD.md next to the runs folder")
    args = parser.parse_args(argv)
    out = args.out or os.path.join(os.path.dirname(os.path.abspath(args.runs_dir)),
                                   "LEADERBOARD.md")
    with open(out, "w", newline="\n") as handle:
        handle.write(render(load_runs(args.runs_dir)))
    return out


if __name__ == "__main__":
    print(main())
